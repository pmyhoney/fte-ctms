-- KOL 탭: 분야별 하위 탭(kol_categories) + 관리자가 지정한 회원의 입력·수정·삭제
--   관리자는 '팀원 관리 > 회원 승인'에서 회원별로 'KOL 편집'을 켜고 끈다 (profiles.kol_editor — 수정은 계속 관리자만).
--   편집 권한: 관리자 또는 kol_editor로 지정된 승인 회원. 조회는 지금처럼 승인 회원 누구나.

-- 1) 편집 담당자 지정 ---------------------------------------------------------------
alter table public.profiles add column kol_editor boolean not null default false;

create function public.can_edit_kol() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from profiles where id = auth.uid() and approved and (role = 'admin' or kol_editor));
$$;

-- 2) 하위 탭(분야) ------------------------------------------------------------------
create table public.kol_categories (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  description text not null default '',
  sort integer not null default 0,
  created_at timestamptz not null default now()
);
insert into public.kol_categories (name, description, sort) values
  ('순환기', '대한고혈압학회·대한심장학회·대한심부전학회 임원 및 로제텔 임상연구 참여 PI 통합 명단', 1),
  ('내분비', '', 2),
  ('이식/면역', '', 3),
  ('항암', '', 4);

alter table public.kol_categories enable row level security;
create policy "승인 회원 조회" on public.kol_categories for select to authenticated using (public.is_approved());
create policy "KOL 편집자 추가" on public.kol_categories for insert to authenticated with check (public.can_edit_kol());
create policy "KOL 편집자 수정" on public.kol_categories for update to authenticated using (public.can_edit_kol()) with check (public.can_edit_kol());
create policy "KOL 편집자 삭제" on public.kol_categories for delete to authenticated using (public.can_edit_kol());
revoke all on public.kol_categories from anon;
grant select, insert, update, delete on public.kol_categories to authenticated;

-- 3) KOL 명단: 기존 명단은 모두 '순환기'로, 새 명단은 id 자동 부여 ----------------------
-- 하위 탭을 지우면 그 탭의 명단도 함께 지워진다 (앱에서 탭 이름을 다시 입력해야 지울 수 있음)
alter table public.kols add column category_id uuid references public.kol_categories(id) on delete cascade;
update public.kols set category_id = (select id from public.kol_categories where name = '순환기');
alter table public.kols alter column category_id set not null;
alter table public.kols alter column id add generated by default as identity;
select setval(pg_get_serial_sequence('public.kols', 'id'), (select coalesce(max(id), 0) + 1 from public.kols), false);

create policy "KOL 편집자 추가" on public.kols for insert to authenticated with check (public.can_edit_kol());
create policy "KOL 편집자 수정" on public.kols for update to authenticated using (public.can_edit_kol()) with check (public.can_edit_kol());
create policy "KOL 편집자 삭제" on public.kols for delete to authenticated using (public.can_edit_kol());
grant insert, update, delete on public.kols to authenticated;
